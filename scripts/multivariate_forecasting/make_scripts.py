"""Per-dataset run scripts of DLT-dyn and the six baselines: scripts/multivariate_forecasting/<group>/<model>[_<dataset>].sh.

    python scripts/multivariate_forecasting/make_scripts.py            # write every script
    python scripts/multivariate_forecasting/make_scripts.py --check    # exit 1 if a script differs from its profile

DLT-dyn follows src/configs/dlt_profiles.py (the paper's stand-alone recipe; Solar and PEMS with the protocol of the
official loaders), the baselines follow src/configs/baseline_profiles.py (the settings of their official scripts
with that protocol, as in the baseline check). The scripts are generated: change a profile, then run this again.
Every script runs all horizons of its dataset for the seeds in $SEEDS (default 2021 2022 2023) and writes one row
per run into output/long_term_forecast/<dataset>.tsv; run_all_forecasts.sh schedules them over GPUs.
"""
import argparse
import shlex
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
from src.configs import baseline_profiles, dlt_profiles  # noqa: E402

GROUPS = {"ETTh1": "ETT", "ETTh2": "ETT", "ETTm1": "ETT", "ETTm2": "ETT", "Weather": "Weather", "ECL": "ECL",
          "Exchange": "Exchange", "Traffic": "Traffic", "Solar": "SolarEnergy",
          "PEMS03": "PEMS", "PEMS04": "PEMS", "PEMS07": "PEMS", "PEMS08": "PEMS"}
MODELS = ("DLT",) + baseline_profiles.BASELINES
SEEDS = "2021 2022 2023"


def script_path(model, ds):
    group = GROUPS[ds]
    shared = sum(1 for d in GROUPS.values() if d == group) > 1
    return HERE / group / ("{}_{}.sh".format(model, ds) if shared else "{}.sh".format(model))


def quote(t):
    """Shell variables of the script expand (double quotes), everything else is literal."""
    if "$" in t:
        return t if t.startswith('"') else '"{}"'.format(t)
    return shlex.quote(t)


def flag_lines(args, indent):
    """One flag (with its value) per line, the layout of the framework's scripts."""
    out, tokens = [], shlex.split(args) if isinstance(args, str) else list(args)
    for t in tokens:
        if t.startswith("--") or not out:
            out.append(t)
        else:
            out[-1] += " " + quote(t)
    return [indent + line + " \\" for line in out]


def header(model, ds, horizons, source):
    rel = script_path(model, ds).relative_to(HERE.parents[1])
    name = "DLT-dyn" if model == "DLT" else baseline_profiles.DISPLAY.get(model, model)
    return [
        "#!/bin/bash",
        "# {} on {}: input 96, horizons {}; {}.".format(name, ds, " ".join(map(str, horizons)), source),
        "# Generated by scripts/multivariate_forecasting/make_scripts.py: change the profile and generate again.",
        "#   bash {}                                   seeds {}".format(rel, SEEDS),
        '#   SEEDS="2021" EXTRA_ARGS="--no_use_gpu --num_workers 0" bash {}   one seed on the CPU'.format(rel),
        "# Results: output/long_term_forecast/{}.tsv (one row per run); checkpoints: temp/checkpoints/{}/.".format(ds, ds),
        "export CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-0}",
        'cd "$(dirname "$0")/../../.."',
        'root="$(python -m src.utils.paths root {})/"'.format(dlt_profiles.DATASET_META[ds]["data_path"]),
        "seeds=(${SEEDS:-" + SEEDS + "})",
        "",
    ]


def meta_args(ds, H, label_len, pred_len_var=None):
    meta = dlt_profiles.resolve_meta(ds, H, label_len=label_len)
    meta["root_path"] = '"$root"'
    if pred_len_var:
        meta["pred_len"] = pred_len_var
        meta["model_id"] = "{}_96_{}".format(ds, pred_len_var)
    return meta


def dlt_script(ds):
    horizons = dlt_profiles.get_pred_lens(ds)
    cfgs = {H: dlt_profiles.resolve(ds, H) for H in horizons}
    assert all(c == cfgs[horizons[0]] for c in cfgs.values()), "the DLT recipe of {} depends on the horizon".format(ds)
    meta = meta_args(ds, horizons[0], None, "$pred_len")
    args = ["--is_training", "1", "--model", "DLT", "--des", "{}_${{pred_len}}_dltdyn".format(ds), "--seed", "$seed"]
    args += dlt_profiles.emit_cli_args(cfgs[horizons[0]], meta)
    lines = header("DLT", ds, horizons, "the stand-alone recipe of the paper (src/configs/dlt_profiles.py)")
    lines += ["for pred_len in {}; do".format(" ".join(map(str, horizons))), '  for seed in "${seeds[@]}"; do',
              "    python -u scripts/run.py \\"]
    lines += flag_lines(args, "      ") + ["      $EXTRA_ARGS", "  done", "done", ""]
    return "\n".join(lines)


def baseline_script(model, ds):
    horizons = dlt_profiles.get_pred_lens(ds)
    lines = header(model, ds, horizons, "settings of the official scripts, protocol of the official loaders")
    for H in horizons:
        settings, source = baseline_profiles.args(model, ds, H)
        meta = meta_args(ds, H, 48)
        args = ["--is_training", "1", "--model", model, "--des", "{}_{}_{}".format(ds, H, model), "--seed", "$seed"]
        args += dlt_profiles.emit_cli_args(dlt_profiles.protocol(ds), meta)
        args += shlex.split(settings) + shlex.split(baseline_profiles.runtime_args(model, ds))
        lines += ["# horizon {}: {}".format(H, source), 'for seed in "${seeds[@]}"; do', "  python -u scripts/run.py \\"]
        lines += flag_lines(args, "    ") + ["    $EXTRA_ARGS", "done", ""]
    return "\n".join(lines)


def scripts():
    for ds in GROUPS:
        for model in MODELS:
            yield script_path(model, ds), dlt_script(ds) if model == "DLT" else baseline_script(model, ds)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="only compare the scripts on disk with their profiles")
    a = p.parse_args()
    stale = []
    for path, text in scripts():
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        path.chmod(0o755)
    if a.check:
        for path in stale:
            print("out of date: {}".format(path.relative_to(HERE.parents[1])))
        sys.exit(1 if stale else 0)
    print("{} scripts written under {}".format(len(GROUPS) * len(MODELS), HERE.relative_to(HERE.parents[1])))


if __name__ == "__main__":
    main()
